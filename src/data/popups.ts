/** 오늘(KST) 게시 중인 팝업 */
export function activePopups(now: Date = new Date()): PopupItem[] {
  const today = new Date(now.getTime() + 9 * 3600 * 1000).toISOString().slice(0, 10)
  return POPUPS.filter((p) => today <= p.until && (!p.from || today >= p.from))
}
